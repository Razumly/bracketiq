import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const sharedDirectory = path.join(repoRoot, "shared/icons");
const siteDirectory = path.join(repoRoot, "apps/site/public/icons");
const siteManifestModule = path.join(
  repoRoot,
  "apps/site/src/components/ui/sharedIconManifest.generated.ts",
);
const mobileXmlDirectory = path.join(
  repoRoot,
  "apps/mobile/core/ui/xml-images/shared",
);
const mobileSharedIconsModule = path.join(
  repoRoot,
  "apps/mobile/core/ui/src/commonMain/kotlin/com/razumly/mvp/icons/sharedIcons.generated.kt",
);
const manifestPath = path.join(sharedDirectory, "manifest.json");
const licenseFiles = ["sports/LICENSE"];
const generatedHeader =
  "Generated by scripts/sync-shared-icons.mjs. Do not edit manually.";

const mode = process.argv.slice(2);
if (mode.length !== 1 || !["--write", "--check"].includes(mode[0])) {
  console.error("Usage: node scripts/sync-shared-icons.mjs --write|--check");
  process.exit(2);
}

const isCheck = mode[0] === "--check";

const fail = (message) => {
  throw new Error(message);
};

const readText = (filePath, description = "shared icon file") => {
  try {
    return fs.readFileSync(filePath, "utf8");
  } catch {
    fail(`Missing ${description}: ${path.relative(repoRoot, filePath)}`);
  }
};

const writeText = (filePath, content) => {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, content, "utf8");
};

const normalizeRelativePath = (value, description) => {
  if (
    typeof value !== "string" ||
    value.length === 0 ||
    value.includes("\\") ||
    path.posix.isAbsolute(value) ||
    path.posix.normalize(value) !== value ||
    value.startsWith("../") ||
    value.includes("/../")
  ) {
    fail(`${description} must be a normalized relative path: ${value}`);
  }
  return value;
};

const parseAttributes = (source) => {
  const attributes = {};
  const pattern = /([:\w-]+)\s*=\s*["']([^"']*)["']/g;
  for (const match of source.matchAll(pattern)) {
    attributes[match[1]] = match[2];
  }
  return attributes;
};

const parseNumber = (value, description) => {
  const parsed = Number.parseFloat(value);
  if (!Number.isFinite(parsed)) {
    fail(`${description} must be numeric: ${value}`);
  }
  return parsed;
};

const parseViewBox = (value, key) => {
  const parts = value.split(/[\s,]+/).filter(Boolean).map(Number);
  if (
    parts.length !== 4 ||
    parts.some((part) => !Number.isFinite(part)) ||
    parts[2] <= 0 ||
    parts[3] <= 0
  ) {
    fail(`Shared icon ${key} must use a valid SVG viewBox.`);
  }
  return parts;
};


const parseSvg = (icon, source) => {
  const rootMatch = source.match(/<svg\b([^>]*)>/s);
  if (!rootMatch) {
    fail(`Shared icon ${icon.key} must contain an SVG root.`);
  }
  const rootAttributes = parseAttributes(rootMatch[1]);
  if (rootAttributes.id !== icon.fragment) {
    fail(
      `Shared icon ${icon.key} must set its root id to ${icon.fragment}.`,
    );
  }
  if (!rootAttributes.viewBox) {
    fail(`Shared icon ${icon.key} must declare a viewBox.`);
  }
  const viewBox = parseViewBox(rootAttributes.viewBox, icon.key);
  const paths = [...source.matchAll(/<path\b([^>]*)>/g)].map((match) => {
    const attributes = parseAttributes(match[1]);
    if (!attributes.d) {
      fail(`Shared icon ${icon.key} contains a path without d data.`);
    }
    return attributes;
  });
  if (paths.length === 0) {
    fail(`Shared icon ${icon.key} must contain at least one path.`);
  }
  return { rootAttributes, viewBox, paths };
};

const manifest = JSON.parse(readText(manifestPath, "shared icon manifest"));
if (manifest.version !== 1 || !Array.isArray(manifest.icons)) {
  fail("shared/icons/manifest.json must define version 1 and an icons array.");
}

const icons = manifest.icons;
const keys = icons.map((icon) => icon.key);
const outputFiles = icons.map((icon) => icon.file);
const sourceFiles = icons.map((icon) => icon.source);

if (icons.length < 1) {
  fail("The shared icon manifest must contain at least one icon.");
}
if (new Set(keys).size !== keys.length) {
  fail("Shared icon keys must be unique.");
}
if (new Set(outputFiles).size !== outputFiles.length) {
  fail("Shared icon output files must be unique.");
}
if (new Set(sourceFiles).size !== sourceFiles.length) {
  fail("Shared icon source files must be unique.");
}

const expectedSourceFiles = new Set(["manifest.json", ...licenseFiles]);
const parsedIcons = [];
for (const icon of icons) {
  if (!icon || typeof icon !== "object") {
    fail("Every shared icon manifest entry must be an object.");
  }
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(icon.key)) {
    fail(`Invalid shared icon key: ${icon.key}`);
  }
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(icon.category)) {
    fail(`Invalid shared icon category for ${icon.key}: ${icon.category}`);
  }
  normalizeRelativePath(icon.file, `Shared icon ${icon.key} file`);
  normalizeRelativePath(icon.source, `Shared icon ${icon.key} source`);
  if (!icon.file.endsWith(".svg") || !icon.source.endsWith(".svg")) {
    fail(`Shared icon ${icon.key} file and source must be SVG files.`);
  }
  if (!/^[A-Za-z][A-Za-z0-9-]*$/.test(icon.fragment)) {
    fail(`Invalid SVG fragment for shared icon ${icon.key}: ${icon.fragment}`);
  }
  if (typeof icon.sourceIcon !== "string" || icon.sourceIcon.length === 0) {
    fail(`Shared icon ${icon.key} must declare sourceIcon.`);
  }
  if (typeof icon.approximation !== "boolean") {
    fail(`Shared icon ${icon.key} must declare approximation.`);
  }
  const sourcePath = path.join(sharedDirectory, icon.source);
  const source = readText(sourcePath, `shared icon source for ${icon.key}`);
  const parsedSvg = parseSvg(icon, source);
  expectedSourceFiles.add(icon.source);
  parsedIcons.push({ icon, source, parsedSvg });
}

const walkFiles = (directory) => {
  if (!fs.existsSync(directory)) return [];
  const files = [];
  const visit = (currentDirectory) => {
    for (const entry of fs.readdirSync(currentDirectory, {
      withFileTypes: true,
    })) {
      const entryPath = path.join(currentDirectory, entry.name);
      if (entry.isDirectory()) {
        visit(entryPath);
      } else if (entry.isFile()) {
        files.push(path.relative(directory, entryPath).split(path.sep).join("/"));
      } else {
        fail(`Generated icon entry must be a file or directory: ${entryPath}`);
      }
    }
  };
  visit(directory);
  return files;
};

for (const file of walkFiles(sharedDirectory)) {
  if (!expectedSourceFiles.has(file)) {
    fail(`Unexpected shared icon entry: ${file}`);
  }
}

const sharedIconKeys = icons.map((icon) => icon.key);
const sportIcons = icons.filter((icon) => icon.category === "sports");
const sportIconKeys = sportIcons.map((icon) => icon.key);

const generatedSiteManifest = [
  `// ${generatedHeader}`,
  "",
  "export const SHARED_ICON_KEYS = [",
  ...sharedIconKeys.map((key) => `  ${JSON.stringify(key)},`),
  "] as const;",
  "",
  "export type SharedIconKey = (typeof SHARED_ICON_KEYS)[number];",
  "",
  "export const SHARED_ICON_ASSET_HREFS = {",
  ...icons.map(
    (icon) =>
      `  ${JSON.stringify(icon.key)}: ${JSON.stringify(`/icons/${icon.file}#${icon.fragment}`)},`,
  ),
  "} as const satisfies Record<SharedIconKey, string>;",
  "",
  "export const SHARED_ICON_VIEWBOXES = {",
  ...parsedIcons.map(
    ({ icon, parsedSvg }) =>
      `  ${JSON.stringify(icon.key)}: ${JSON.stringify(parsedSvg.viewBox.join(" "))},`,
  ),
  "} as const satisfies Record<SharedIconKey, string>;",
  "",
  "export const SPORT_ICON_KEYS = [",
  ...sportIconKeys.map((key) => `  ${JSON.stringify(key)},`),
  "] as const;",
  "",
  "export type SportIconKey = (typeof SPORT_ICON_KEYS)[number];",
  "",
  "export const SPORT_ICON_ASSET_HREFS = {",
  ...sportIcons.map(
    (icon) =>
      `  ${JSON.stringify(icon.key)}: SHARED_ICON_ASSET_HREFS[${JSON.stringify(icon.key)}],`,
  ),
  "} as const satisfies Record<SportIconKey, string>;",
  "",
].join("\n");
const productIcons = icons.filter((icon) => icon.category === "product");
const toKotlinName = (key) =>
  key
    .split("-")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");

const generatedMobileSharedIcons = [
  `// ${generatedHeader}`,
  "",
  "package com.razumly.mvp.icons",
  "",
  "import androidx.compose.ui.graphics.vector.ImageVector",
  "import com.razumly.mvp.icons.generated.Images",
  ...productIcons.map(
    (icon) =>
      `import com.razumly.mvp.icons.generated.shared.Product${toKotlinName(icon.key)}`,
  ),
  ...sportIcons.map(
    (icon) =>
      `import com.razumly.mvp.icons.generated.shared.Sports${toKotlinName(icon.key)}`,
  ),
  "",
  "public object SharedIcons {",
  ...productIcons.flatMap((icon) => [
    `    public val ${toKotlinName(icon.key)}: ImageVector`,
    `        get() = Images.Shared.Product${toKotlinName(icon.key)}`,
  ]),
  "}",
  "",
  "public object SportIcons {",
  ...sportIcons.flatMap((icon) => [
    `    public val ${toKotlinName(icon.key)}: ImageVector`,
    `        get() = Images.Shared.Sports${toKotlinName(icon.key)}`,
  ]),
  "",
  "    internal fun keyForName(name: String): String? = when (name) {",
  ...sportIcons.map(
    (icon) =>
      `        ${JSON.stringify(icon.key.replaceAll("-", " "))} -> ${JSON.stringify(icon.key)}`,
  ),
  "        else -> null",
  "    }",
  "",
  "    public operator fun get(key: String): ImageVector = when (key) {",
  ...sportIcons.map(
    (icon) => `        ${JSON.stringify(icon.key)} -> ${toKotlinName(icon.key)}`,
  ),
  "        else -> Other",
  "    }",
  "}",
  "",
].join("\n");

const escapeXml = (value) =>
  value
    .replaceAll("&", "&amp;")
    .replaceAll('"', "&quot;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;");

const formatNumber = (value) => {
  const formatted = Number(value.toFixed(4)).toString();
  return formatted === "-0" ? "0" : formatted;
};

const toAndroidColor = (value, transparent = false) => {
  if (transparent || !value || value === "none") return "#00000000";
  return "#FF000000";
};

const toVectorXml = ({ icon, parsedSvg }) => {
  const { rootAttributes, viewBox, paths } = parsedSvg;
  const width = formatNumber(
    parseNumber(rootAttributes.width ?? viewBox[2].toString(), `${icon.key} width`),
  );
  const height = formatNumber(
    parseNumber(
      rootAttributes.height ?? viewBox[3].toString(),
      `${icon.key} height`,
    ),
  );
  const rootFill = rootAttributes.fill ?? "none";
  const rootStroke = rootAttributes.stroke ?? "none";
  const rootStrokeWidth = rootAttributes["stroke-width"] ?? "1";
  const rootStrokeLinecap = rootAttributes["stroke-linecap"];
  const rootStrokeLinejoin = rootAttributes["stroke-linejoin"];
  const pathXml = paths
    .map((pathAttributes) => {
      const fill = pathAttributes.fill ?? rootFill;
      const stroke = pathAttributes.stroke ?? rootStroke;
      const strokeWidth = pathAttributes["stroke-width"] ?? rootStrokeWidth;
      const strokeLinecap =
        pathAttributes["stroke-linecap"] ?? rootStrokeLinecap;
      const strokeLinejoin =
        pathAttributes["stroke-linejoin"] ?? rootStrokeLinejoin;
      const attributes = [
        `android:pathData="${escapeXml(pathAttributes.d)}"`,
        `android:fillColor="${toAndroidColor(fill === "none" ? "none" : fill, fill === "none")}"`,
      ];
      if (stroke !== "none") {
        attributes.push(`android:strokeColor="${toAndroidColor(stroke)}"`);
        attributes.push(`android:strokeWidth="${escapeXml(strokeWidth)}"`);
        if (strokeLinecap) {
          attributes.push(
            `android:strokeLineCap="${escapeXml(strokeLinecap)}"`,
          );
        }
        if (strokeLinejoin) {
          attributes.push(
            `android:strokeLineJoin="${escapeXml(strokeLinejoin)}"`,
          );
        }
      }
      return `    <path ${attributes.join(" ")} />`;
    })
    .join("\n");
  const xmlFileName = `${icon.category}_${icon.key.replaceAll("-", "_")}.xml`;
  return {
    fileName: xmlFileName,
    content: [
      `<!-- ${generatedHeader} -->`,
      "<vector xmlns:android=\"http://schemas.android.com/apk/res/android\"",
      `  android:width=\"${width}dp\"`,
      `  android:height=\"${height}dp\"`,
      `  android:viewportWidth=\"${formatNumber(viewBox[2])}\"`,
      `  android:viewportHeight=\"${formatNumber(viewBox[3])}\">`,
      pathXml,
      "</vector>",
      "",
    ].join("\n"),
  };
};

const mobileVectors = parsedIcons.map(toVectorXml);
const expectedMobileFiles = new Set(mobileVectors.map((vector) => vector.fileName));
for (const file of walkFiles(mobileXmlDirectory)) {
  if (!expectedMobileFiles.has(file)) {
    fail(`Unexpected generated mobile icon entry: ${file}`);
  }
}

const expectedSiteFiles = new Set([
  ...licenseFiles,
  ...outputFiles,
]);
const managedSiteDirectories = new Set(
  [...expectedSiteFiles].map((file) => file.split("/")[0]),
);
const isManagedSiteFile = (file) =>
  managedSiteDirectories.has(file.split("/")[0]);
for (const file of walkFiles(siteDirectory)) {
  if (isManagedSiteFile(file) && !expectedSiteFiles.has(file)) {
    fail(`Unexpected generated site icon entry: ${file}`);
  }
}

const mismatches = [];
for (const licenseFile of licenseFiles) {
  const source = readText(path.join(sharedDirectory, licenseFile));
  const targetPath = path.join(siteDirectory, licenseFile);
  if (!fs.existsSync(targetPath) || fs.readFileSync(targetPath, "utf8") !== source) {
    mismatches.push(path.relative(repoRoot, targetPath));
  }
}
for (const { icon, source } of parsedIcons) {
  const targetPath = path.join(siteDirectory, icon.file);
  if (!fs.existsSync(targetPath) || fs.readFileSync(targetPath, "utf8") !== source) {
    mismatches.push(path.relative(repoRoot, targetPath));
  }
}
if (
  !fs.existsSync(siteManifestModule) ||
  fs.readFileSync(siteManifestModule, "utf8") !== generatedSiteManifest
) {
  mismatches.push(path.relative(repoRoot, siteManifestModule));
}
if (
  !fs.existsSync(mobileSharedIconsModule) ||
  fs.readFileSync(mobileSharedIconsModule, "utf8") !== generatedMobileSharedIcons
) {
  mismatches.push(path.relative(repoRoot, mobileSharedIconsModule));
}
for (const vector of mobileVectors) {
  const targetPath = path.join(mobileXmlDirectory, vector.fileName);
  if (
    !fs.existsSync(targetPath) ||
    fs.readFileSync(targetPath, "utf8") !== vector.content
  ) {
    mismatches.push(path.relative(repoRoot, targetPath));
  }
}

if (isCheck) {
  if (mismatches.length > 0) {
    fail(
      `Generated shared icon files are out of date:\n${mismatches
        .map((file) => `- ${file}`)
        .join("\n")}\nRun the sync command with --write.`,
    );
  }
  console.log(`Shared icon projections are current (${icons.length} icons).`);
  process.exit(0);
}

for (const file of walkFiles(siteDirectory)) {
  if (isManagedSiteFile(file) && !expectedSiteFiles.has(file)) {
    fs.unlinkSync(path.join(siteDirectory, file));
  }
}
for (const file of walkFiles(mobileXmlDirectory)) {
  if (!expectedMobileFiles.has(file)) {
    fs.unlinkSync(path.join(mobileXmlDirectory, file));
  }
}
for (const licenseFile of licenseFiles) {
  writeText(
    path.join(siteDirectory, licenseFile),
    readText(path.join(sharedDirectory, licenseFile)),
  );
}
for (const { icon, source } of parsedIcons) {
  writeText(path.join(siteDirectory, icon.file), source);
}
writeText(siteManifestModule, generatedSiteManifest);
writeText(mobileSharedIconsModule, generatedMobileSharedIcons);
for (const vector of mobileVectors) {
  writeText(path.join(mobileXmlDirectory, vector.fileName), vector.content);
}
console.log(`Synchronized ${icons.length} shared icons.`);
